CREATE TABLE IF NOT EXISTS tipo_residuo (
    id_tipo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clasificacion varchar(30) NOT NULL UNIQUE,
    CONSTRAINT ck_tipo_residuo_clasificacion
        CHECK (clasificacion IN ('APROVECHABLE', 'NO_APROVECHABLE'))
);

CREATE TABLE IF NOT EXISTS contenedor (
    id_contenedor integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(80) NOT NULL UNIQUE,
    capacidad_maxima integer NOT NULL,
    nivel_actual integer NOT NULL DEFAULT 0,
    estado varchar(30) NOT NULL,
    CONSTRAINT ck_contenedor_niveles CHECK (capacidad_maxima > 0 AND nivel_actual >= 0)
);

CREATE TABLE IF NOT EXISTS residuo (
    id_residuo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tipo integer NOT NULL REFERENCES tipo_residuo (id_tipo) ON DELETE RESTRICT,
    id_contenedor integer NOT NULL REFERENCES contenedor (id_contenedor) ON DELETE RESTRICT,
    fecha_hora_deteccion timestamp with time zone NOT NULL,
    confianza_clasificacion numeric(5,4) NOT NULL,
    imagen_url varchar(2048),
    CONSTRAINT ck_residuo_confianza CHECK (confianza_clasificacion >= 0 AND confianza_clasificacion <= 1)
);

CREATE INDEX IF NOT EXISTS ix_residuo_fecha_hora_deteccion
    ON residuo (fecha_hora_deteccion DESC);
